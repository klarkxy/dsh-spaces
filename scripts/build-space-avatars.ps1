$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = Split-Path $PSScriptRoot -Parent
$folder = Join-Path $root 'resources/space-avatars'
$entries = Get-Content -Raw (Join-Path $folder 'generation.json') | ConvertFrom-Json
$rows = foreach ($entry in $entries) {
  $source = [System.Drawing.Image]::FromFile((Join-Path $folder ($entry.id + '.png')))
  $bitmap = [System.Drawing.Bitmap]::new(128, 128)
  $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
  $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
  $graphics.DrawImage($source, 0, 0, 128, 128)
  $stream = [System.IO.MemoryStream]::new()
  $bitmap.Save($stream, [System.Drawing.Imaging.ImageFormat]::Png)
  $image = 'data:image/png;base64,' + [Convert]::ToBase64String($stream.ToArray())
  $graphics.Dispose(); $bitmap.Dispose(); $source.Dispose(); $stream.Dispose()
  @{ id = $entry.id; zh = $entry.zh; en = $entry.en; image = $image }
}
$json = ConvertTo-Json -InputObject @($rows | Where-Object { $_.id -ne "desktop-maid" }) -Depth 4 -Compress
$desktop = ConvertTo-Json -InputObject ($rows | Where-Object { $_.id -eq "desktop-maid" }).image -Compress
$module = @'
// Generated by scripts/build-space-avatars.ps1 from resources/space-avatars.
// Store the selected image in the existing icon field; no new persisted format.
export const DESKTOP_AVATAR_IMAGE = __DESKTOP__;
export const SPACE_AVATARS: readonly { id: string; zh: string; en: string; image: string }[] = __JSON__;

/** Stable for existing spaces without a custom icon, independent of list order. */
export function defaultSpaceAvatar(spaceId: string) {
  let hash = 0;
  for (const character of spaceId) hash = (Math.imul(hash, 31) + character.codePointAt(0)!) >>> 0;
  return SPACE_AVATARS[hash % SPACE_AVATARS.length];
}
'@
[IO.File]::WriteAllText((Join-Path $root 'src/shared/space-avatars.ts'), $module.Replace('__JSON__', $json).Replace('__DESKTOP__', $desktop), [Text.UTF8Encoding]::new($false))
Write-Output ('Built {0} avatars ({1} bytes)' -f $rows.Count, (Get-Item (Join-Path $root 'src/shared/space-avatars.ts')).Length)
