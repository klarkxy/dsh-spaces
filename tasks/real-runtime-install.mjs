import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { RuntimeStore } from '../src/main/runtime-store.ts';
const root = mkdtempSync(join(tmpdir(), 'spaces-runtime-install-'));
console.log(`RUNTIME_INSTALL_ROOT=${root}`);
const source = process.env.DSH_TEST_PACKAGE_SOURCE === 'china' ? 'china' : 'official';
const store = new RuntimeStore({ root, source: () => source, legacy: () => undefined });
const catalog = await store.catalog();
const version = process.env.DSH_TEST_RUNTIME_VERSION || '0.1.5-rc.1';
assert.ok(catalog.versions.some(row => row.version === version), `Catalog does not contain ${version}`);
console.log(`PASS ${source} catalog: ${catalog.versions.length} exact versions`);
const installed = await store.install(version);
assert.equal(store.current(), undefined);
console.log('PASS real exact-version npm installation and version probe; current remains unchanged');
store.select(installed.version);
assert.equal(store.current().bin, installed.bin);
writeFileSync(process.env.DSH_TEST_INSTALL_RESULT || 'tasks/runtime-install-result.json', JSON.stringify({ root, source, installed }, null, 2));
console.log(`INSTALLED_RUNTIME=${installed.bin}`);
