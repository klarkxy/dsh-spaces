import assert from 'node:assert/strict';
import { join } from 'node:path';
import { readFileSync, writeFileSync } from 'node:fs';
import { bin, home } from './real-config-check.mjs';
import { setSelectedDshResolver } from '../src/adapters/node/dsh-cli.ts';
import { DiagnosticsService } from '../src/adapters/node/diagnostics.ts';
import { ProfileRegistry } from '../src/adapters/node/profile-registry.ts';
setSelectedDshResolver(() => bin);
const registry = new ProfileRegistry(home);
let stopped = false;
const service = new DiagnosticsService({ home, profiles: () => registry.scan(),
  statusOf: () => 'stopped', stop: async () => { stopped = true; }, isMaintenance: () => false });
const patch = join(home, 'profiles', 'coding', 'cordis.patch.yml');
const original = readFileSync(patch, 'utf8');
const backupId = 'cordis.patch.yml.bak-acceptance';
writeFileSync(join(home, 'profiles', 'coding', backupId), original);
writeFileSync(patch, original + '\n# current-change\n');
assert.equal(service.previewBackup('coding', backupId).content, original);
await service.restoreBackup('coding', backupId);
assert.ok(stopped);
assert.ok(!readFileSync(patch, 'utf8').includes('current-change'));
const after = readFileSync(patch, 'utf8');
const badId = 'cordis.patch.yml.bak-invalid';
writeFileSync(join(home, 'profiles', 'coding', badId), 'services: !!js "getServices()"\n');
await assert.rejects(service.restoreBackup('coding', badId));
assert.equal(readFileSync(patch, 'utf8'), after);
service.record('coding', 'stderr', 'password: "alpha beta"');
assert.ok(!JSON.stringify(service.get('coding')).includes('alpha beta'));
console.log('PASS real diagnostics preview, restore, DSH verification, rollback and redaction');
