export const WORKBENCH_MESSAGES: Record<WorkbenchLocale, Record<WorkbenchMessageKey, string>> = {
  en,
  zh,
};

const VAGUE_REASONS = new Set([
  "The workbench cannot complete this request.",
  "The workbench cannot accept this request.",
  "The workbench service could not complete this request.",
  "The workbench request failed.",
  "The job failed.",
  "The maintenance operation failed.",
  "工作台无法完成该请求。",
]);

/** Date and time in the reader's locale. */
export function formatDateTime(locale: WorkbenchLocale, iso: string): string {
  return new Intl.DateTimeFormat(locale === "en" ? "en" : "zh-CN", { dateStyle: "medium", timeStyle: "short" }).format(new Date(iso));
}

/** A byte count as megabytes in the reader's locale. */
export function formatMegabytes(locale: WorkbenchLocale, bytes: number): string {
  const value = new Intl.NumberFormat(locale === "en" ? "en" : "zh-CN", { maximumFractionDigits: 1 }).format(bytes / 1048576);
  return `${value} MB`;
}

export function t(locale: WorkbenchLocale, key: WorkbenchMessageKey, vars?: Record<string, string>): string {
  const template = WORKBENCH_MESSAGES[locale][key] ?? WORKBENCH_MESSAGES.en[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => vars[name] ?? "");
}

const KNOWN_REASON_TO_KEY: Record<string, WorkbenchMessageKey> = {
  "The preview expired. Request a new preview.": "error.previewExpired",
  "The target changed. Request a new preview.": "error.targetChanged",
  "The preview belongs to another service epoch.": "error.epochChanged",
};

